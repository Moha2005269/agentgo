// Compares the named-tool register of the graduation roadmap (the brief's
// full tool list) with what the browser really implements.
//   node scripts/dev/coverage.js            summary per domain
//   node scripts/dev/coverage.js --missing  also list every missing name
//   node scripts/dev/coverage.js --write    rewrite docs/tool-coverage.md
// "Implemented" means: the command is in the registry with an integration
// test, either under its own name or as a registered alias of one that is.
const fs = require("node:fs");
const path = require("node:path");

const repo = path.resolve(__dirname, "../..");
const roadmap = process.env.AGENTGO_ROADMAP || path.join(repo, "docs", "tool-register.md");
const unused =
  path.resolve(repo, "../../../2026-10-05/vehicle-to-roadside-v2r-communications-support/outputs/agentgo-graduation-roadmap.md");
const register = fs.readFileSync(roadmap, "utf8").split("<!-- TOOL_REGISTER_START -->")[1] || "";
const domains = [];
for (const line of register.split("\n")) {
  const heading = line.match(/^### (\d+)\. (.+)/);
  if (heading) domains.push({ id: Number(heading[1]), name: heading[2].trim(), tools: [] });
  const tool = line.match(/^- \[.\] `([^`]+)`/);
  if (tool && domains.length) domains.at(-1).tools.push(tool[1]);
}

const methods = fs.readFileSync(path.join(repo, "crates/agentgo-shell-bridge/src/methods.rs"), "utf8");
const implemented = new Set();
for (const m of methods.matchAll(/\(\s*"([a-z_.0-9]+)",\s*"(?:[^"\\]|\\.)*",\s*\d+,\s*"([^"]*)",?\s*\)/g)) if (m[2]) implemented.add(m[1]);
const aliasFile = path.join(repo, "crates/agentgo-shell-bridge/src/extra.rs");
const aliases = new Map();
if (fs.existsSync(aliasFile)) {
  for (const m of fs.readFileSync(aliasFile, "utf8").split("pub const PLANNED")[0].matchAll(/\(\s*"([a-z_.0-9]+)",\s*"(?:[^"\\]|\\.)*",\s*"(alias|page|cdp)",\s*"([A-Za-z_.0-9]+)"/g)) aliases.set(m[1], m[2] === "alias" ? m[3] : "observe.page");
}
const unsupported = new Map();
if (fs.existsSync(aliasFile)) {
  const table = fs.readFileSync(aliasFile, "utf8").split("pub const UNSUPPORTED")[1] || "";
  for (const m of table.matchAll(/\(\s*"([a-z_.0-9]+)",\s*"((?:[^"\\]|\\.)*)"\)/g)) unsupported.set(m[1], m[2]);
}

const status = (name) => implemented.has(name) ? "native" : implemented.has(aliases.get(name)) ? "alias" : unsupported.has(name) ? "unsupported" : "missing";
let total = 0;
const count = { native: 0, alias: 0, unsupported: 0, missing: 0 };
const rows = [];
const missing = [];
for (const domain of domains) {
  const here = { native: 0, alias: 0, unsupported: 0, missing: 0 };
  for (const tool of domain.tools) {
    const s = status(tool);
    here[s] += 1;
    count[s] += 1;
    total += 1;
    if (s === "missing") missing.push(`${domain.id} ${tool}`);
  }
  rows.push(`| ${domain.id}. ${domain.name} | ${domain.tools.length} | ${here.native} | ${here.alias} | ${here.unsupported} | ${here.missing} |`);
}
const summary = `${total} named tools: ${count.native} implemented under their own name, ${count.alias} as aliases, ${count.unsupported} declared unsupported, ${count.missing} missing`;
console.log(summary);
if (!process.argv.includes("--quiet")) console.log(rows.join("\n"));
if (process.argv.includes("--missing")) console.log(missing.join("\n"));
if (process.argv.includes("--write")) {
  fs.writeFileSync(path.join(repo, "docs", "tool-coverage.md"), `# Coverage of the brief's tool list

Generated by \`node scripts/dev/coverage.js --write\`. The list is the named-tool
register of the graduation roadmap (${total} names in ${domains.length} domains).

**${summary}.**

- *Own name*: a registry command with an integration test.
- *Alias*: the name is accepted and runs a tested command with the same effect.
- *Unsupported*: the browser answers \`unsupported\` with the reason (an engine
  or platform limit, or a deliberate safety decision).
- *Missing*: not accepted at all yet.

| Domain | Tools | Own name | Alias | Unsupported | Missing |
|---|---:|---:|---:|---:|---:|
${rows.join("\n")}

## Missing

${missing.length ? missing.map((m) => `- \`${m.split(" ")[1]}\` (domain ${m.split(" ")[0]})`).join("\n") : "None."}
`);
}
