// Release audit: dependency licences and a secret scan.
//   node scripts/dev/audit.js            check; exit 1 on a problem
//   node scripts/dev/audit.js --write    also rewrite docs/licenses.md
const { execFileSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");

const repo = path.resolve(__dirname, "../..");
let problems = 0;

// ---- licences ---------------------------------------------------------------
const metadata = JSON.parse(execFileSync("cargo", ["metadata", "--offline", "--format-version", "1", "--locked"], { cwd: repo, encoding: "utf8", maxBuffer: 256 * 1024 * 1024 }));
const own = new Set(metadata.workspace_members);
const packages = metadata.packages.filter((p) => !own.has(p.id)).sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
// Licences that allow shipping inside an Apache-2.0/MIT project without
// passing obligations on to the whole program.
const accepted = /^(MIT|Apache-2\.0|BSD-2-Clause|BSD-3-Clause|ISC|Zlib|Unicode-3\.0|Unicode-DFS-2016|CC0-1\.0|Unlicense|0BSD|BSL-1\.0|MPL-2\.0|CDLA-Permissive-2\.0|Apache-2\.0 WITH LLVM-exception|OpenSSL)$/;
const ok = (expression) => {
  if (!expression) return false;
  // "A OR B": one acceptable choice is enough. "A AND B": every part must be.
  return expression.split(/\s+OR\s+|\s*\/\s*/).some((choice) => choice.replace(/[()]/g, "").split(/\s+AND\s+/).every((part) => accepted.test(part.trim())));
};
const rows = [];
for (const p of packages) {
  const good = ok(p.license);
  if (!good) {
    problems += 1;
    console.log(`LICENCE  ${p.name} ${p.version}: ${p.license || "none declared"}`);
  }
  rows.push(`| ${p.name} | ${p.version} | ${p.license || "none declared"} |${good ? "" : " **review**"}`);
}
console.log(`licences: ${packages.length} third-party crates, ${problems} to review`);
if (process.argv.includes("--write")) {
  fs.writeFileSync(path.join(repo, "docs", "licenses.md"), `# Third-party licences

Generated by \`node scripts/dev/audit.js --write\` from \`cargo metadata\` (locked
versions). AgentGo also ships the Chromium Embedded Framework; its licences are
in \`THIRD-PARTY-CREDITS.html\` inside every package.

${packages.length} crates. Accepted licences: MIT, Apache-2.0, BSD, ISC, Zlib,
Unicode, CC0, Unlicense, BSL-1.0, MPL-2.0 (file-level copyleft, unmodified).

| Crate | Version | Licence |
|---|---|---|
${rows.join("\n")}
`);
}

// ---- secrets ----------------------------------------------------------------
const skip = /^(target|dist|third_party|node_modules|\.git)([\\/]|$)/;
const textFile = /\.(rs|toml|js|mjs|json|md|html|css|ps1|py|yml|yaml|txt|lock|cmd|sh)$/i;
const patterns = [
  ["private key", /-----BEGIN (?:RSA |EC |OPENSSH |DSA |PGP )?PRIVATE KEY/],
  ["AWS access key", /\bAKIA[0-9A-Z]{16}\b/],
  ["GitHub token", /\bgh[pousr]_[A-Za-z0-9]{36,}\b/],
  ["Google API key", /\bAIza[0-9A-Za-z_-]{35}\b/],
  ["Google OAuth secret", /\bGOCSPX-[A-Za-z0-9_-]{20,}\b/],
  ["Slack token", /\bxox[baprs]-[A-Za-z0-9-]{10,}\b/],
  ["Anthropic or OpenAI key", /\bsk-(?:ant-)?[A-Za-z0-9_-]{32,}\b/],
  ["assigned secret", /(?:api[_-]?key|client[_-]?secret|password|passwd|token)["']?\s*[:=]\s*["'][A-Za-z0-9+/_-]{24,}["']/i],
];
let scanned = 0;
const walk = (dir) => {
  for (const entry of fs.readdirSync(path.join(repo, dir), { withFileTypes: true })) {
    const rel = path.join(dir, entry.name);
    if (skip.test(rel)) continue;
    if (entry.isDirectory()) walk(rel);
    else if (textFile.test(entry.name) && fs.statSync(path.join(repo, rel)).size < 2_000_000) {
      scanned += 1;
      const lines = fs.readFileSync(path.join(repo, rel), "utf8").split("\n");
      lines.forEach((line, index) => {
        for (const [what, pattern] of patterns) {
          // The scanner's own patterns and its allow-list marker are not secrets.
          if (pattern.test(line) && !line.includes("audit:allow") && rel !== path.join("scripts", "dev", "audit.js")) {
            problems += 1;
            console.log(`SECRET   ${rel}:${index + 1}: ${what}`);
          }
        }
      });
    }
  }
};
walk("");
console.log(`secrets: ${scanned} files scanned`);
process.exit(problems ? 1 : 0);
