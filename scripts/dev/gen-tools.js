// Generates crates/agentgo-shell-bridge/src/extra.rs from scripts/dev/tools-spec.js
// and docs/tool-register.md:
//   EXTRA   the commands of the spec (aliases of existing commands and page tools)
//   PLANNED every other name of the register: accepted and answered with
//           capability.unsupported, so nothing in the register is unknown.
//   node scripts/dev/gen-tools.js [--check]
const fs = require("node:fs");
const path = require("node:path");
const spec = require("./tools-spec");

const repo = path.resolve(__dirname, "../..");
const methods = fs.readFileSync(path.join(repo, "crates/agentgo-shell-bridge/src/methods.rs"), "utf8");
const core = new Map();
for (const m of methods.matchAll(/\(\s*"([a-z_.0-9]+)",\s*"(?:[^"\\]|\\.)*",\s*\d+,\s*"([^"]*)",?\s*\)/g)) core.set(m[1], Boolean(m[2]));
const register = [...fs.readFileSync(path.join(repo, "docs/tool-register.md"), "utf8").matchAll(/^- \[.\] `([^`]+)`/gm)].map((m) => m[1]);
const tools = fs.readFileSync(path.join(repo, "crates/agentgo-cef/src/runtime/tools.js"), "utf8");

// A page-tools file that does not parse would break every page tool at once.
const toolsFile = path.join(repo, "crates/agentgo-cef/src/runtime/tools.js");
for (const script of [toolsFile, path.join(repo, "crates/agentgo-cef/src/runtime/agent.js")]) require("node:child_process").execFileSync(process.execPath, ["--check", script], { stdio: "inherit" });
const quote = (text) => JSON.stringify(String(text));
const rows = [];
const seen = new Set();
const problems = [];
const add = (name, description, kind, target, preset) => {
  if (seen.has(name)) problems.push(`${name} is listed twice`);
  if (core.get(name)) problems.push(`${name} already is a core command`);
  if (!register.includes(name)) problems.push(`${name} is not in the tool register`);
  seen.add(name);
  rows.push(`    (${quote(name)}, ${quote(description)}, ${quote(kind)}, ${quote(target)}, ${quote(preset)}),`);
};
for (const [name, target, preset, description] of spec.aliases) {
  if (!core.get(target)) problems.push(`${name}: target ${target} is not an implemented core command`);
  add(name, description, "alias", target, JSON.stringify(preset));
}
for (const [name, description] of spec.page) {
  if (!tools.includes(`'${name}':`)) problems.push(`${name} has no implementation in tools.js`);
  add(name, description, "page", name, "{}");
}
for (const [name, method, defaults, description] of spec.cdp) {
  if (!/^[A-Z][A-Za-z]+\.[a-z][A-Za-z]+$/.test(method)) problems.push(`${name}: ${method} is not a DevTools method`);
  add(name, description, "cdp", method, JSON.stringify(defaults));
}
const unsupportedRows = [];
for (const [name, reason] of spec.unsupported) {
  if (seen.has(name) || core.get(name)) problems.push(`${name} is built and declared unsupported`);
  if (!register.includes(name)) problems.push(`${name} is not in the tool register`);
  seen.add(name);
  unsupportedRows.push(`    (${quote(name)}, ${quote(reason)}),`);
}
if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}
const planned = register.filter((name) => !core.get(name) && !seen.has(name));
const out = `//! Generated by \`node scripts/dev/gen-tools.js\` from \`scripts/dev/tools-spec.js\`
//! and \`docs/tool-register.md\`. Do not edit by hand.

/// Commands of the tool register that are carried out by another command
/// (\`alias\`: target command and preset parameters), by a page tool
/// (\`page\`: its name in \`tools.js\`) or by one DevTools method (\`cdp\`:
/// method and default parameters). Each has a case in the \`tools_e2e\` test.
/// Fields: name, description, kind, target, preset parameters as JSON.
pub const EXTRA: &[(&str, &str, &str, &str, &str)] = &[
${rows.join("\n")}
];

/// Names of the tool register that are not built yet. They are accepted and
/// answered with \`capability.unsupported\`.
pub const PLANNED: &[&str] = &[
${planned.map((name) => `    ${quote(name)},`).join("\n")}
];

/// The extra command called \`name\`.
pub fn find(name: &str) -> Option<&'static (&'static str, &'static str, &'static str, &'static str, &'static str)> {
    EXTRA.iter().find(|extra| extra.0 == name)
}

/// Whether \`name\` is in the register but not built.
pub fn planned(name: &str) -> bool {
    PLANNED.contains(&name)
}

/// Names of the register this browser cannot provide, with the reason.
pub const UNSUPPORTED: &[(&str, &str)] = &[
${unsupportedRows.join("\n")}
];

/// Why \`name\` cannot be provided, when it is declared unsupported.
pub fn unsupported(name: &str) -> Option<&'static str> {
    UNSUPPORTED.iter().find(|entry| entry.0 == name).map(|entry| entry.1)
}
`;
const file = path.join(repo, "crates/agentgo-shell-bridge/src/extra.rs");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== out) {
    console.error("extra.rs is out of date; run node scripts/dev/gen-tools.js");
    process.exit(1);
  }
} else {
  fs.writeFileSync(file, out);
}
console.log(`${rows.length} extra commands (${spec.aliases.length} aliases, ${spec.page.length} page tools, ${spec.cdp.length} DevTools), ${spec.unsupported.length} unsupported, ${planned.length} planned`);
