// Writes skills/agentgo/references/commands.md from the command registry, so
// the reference an agent reads always matches the browser it talks to.
//   node scripts/dev/gen-skill.js          rewrite the file
//   node scripts/dev/gen-skill.js --check  fail when it is out of date
const fs = require("node:fs");
const path = require("node:path");

const repo = path.resolve(__dirname, "../..");
const source = fs.readFileSync(path.join(repo, "crates/agentgo-shell-bridge/src/methods.rs"), "utf8");
const commands = [];
for (const m of source.matchAll(/\(\s*"([a-z_.0-9]+)",\s*"((?:[^"\\]|\\.)*)",\s*(\d+),\s*"([^"]*)",?\s*\)/g)) {
  if (m[4]) commands.push({ name: m[1], text: m[2].replace(/\\"/g, '"') });
}
const extra = fs.readFileSync(path.join(repo, "crates/agentgo-shell-bridge/src/extra.rs"), "utf8").split("pub const PLANNED")[0];
for (const m of extra.matchAll(/\(\s*"([a-z_.0-9]+)",\s*"((?:[^"\\]|\\.)*)",\s*"(alias|page|cdp)",\s*"([A-Za-z_.0-9]+)"/g)) {
  commands.push({ name: m[1], text: m[2].replace(/\\"/g, '"') + (m[3] === "alias" ? ` Same as \`${m[4]}\`.` : "") });
}
// One heading per domain, in the order an agent meets them.
const groups = [
  ["Open and move", ["navigate", "search", "tabs", "tab", "window", "page", "browsing_context", "browser_ui", "viewport", "frame"]],
  ["Read the page", ["observe", "state", "capture", "siteinfo", "site_info", "network", "print", "locate", "extract", "a11y", "evidence", "context", "ground", "debug", "media"]],
  ["Act on the page", ["act", "form", "clipboard", "pointer", "keyboard", "dialog", "wait", "edit", "focus", "selection", "touch", "file"]],
  ["Do several things in one call", ["workflow", "decision", "batch", "collect", "research", "recovery"]],
  ["Accounts, sign-ins and APIs", ["accounts", "credentials", "credential", "connectors", "storage"]],
  ["The person: approvals, handoff, control", ["approval", "handoff", "agent", "audit", "session", "events", "policy", "shell"]],
  ["Browser, profile and files", ["browser", "profile", "settings", "bookmark", "history", "download", "downloads", "runtime", "api", "skill", "theme", "appearance", "browser_settings", "download_manager"]],
];
const used = new Set();
let out = `# AgentGo commands

Generated by \`node scripts/dev/gen-skill.js\` from the browser's command
registry: ${commands.length} commands, each with an integration test. Call any of them
by name (\`browser_call\` over MCP, \`agentgo call\` in a shell). Commands marked
"operator only" answer \`policy.denied\` to agents: they are the person's.
Parameters common to page commands: \`tabId\` (default: your last tab) and, for
actions, \`ref\` from the outline.
`;
for (const [title, domains] of groups) {
  const rows = commands.filter((c) => domains.includes(c.name.split(".")[0]));
  if (!rows.length) continue;
  out += `\n## ${title}\n\n| Command | What it does |\n|---|---|\n`;
  for (const c of rows.sort((a, b) => domains.indexOf(a.name.split(".")[0]) - domains.indexOf(b.name.split(".")[0]) || a.name.localeCompare(b.name))) {
    used.add(c.name);
    out += `| \`${c.name}\` | ${c.text} |\n`;
  }
}
const rest = commands.filter((c) => !used.has(c.name));
if (rest.length) {
  out += `\n## Other\n\n| Command | What it does |\n|---|---|\n`;
  for (const c of rest.sort((a, b) => a.name.localeCompare(b.name))) out += `| \`${c.name}\` | ${c.text} |\n`;
}
const unavailable = [...(fs.readFileSync(path.join(repo, "crates/agentgo-shell-bridge/src/extra.rs"), "utf8").split("pub const UNSUPPORTED")[1] || "")
  .matchAll(/\(\s*"([a-z_.0-9]+)",\s*"((?:[^"\\]|\\.)*)"\)/g)];
if (unavailable.length) {
  out += `\n## Not available in AgentGo\n\nThese names answer \`capability.unsupported\` with the reason; do not plan around them.\n\n| Command | Why |\n|---|---|\n`;
  for (const [, name, reason] of unavailable) out += `| \`${name}\` | ${reason} |\n`;
}
const file = path.join(repo, "skills/agentgo/references/commands.md");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== out) {
    console.error("skills/agentgo/references/commands.md is out of date; run node scripts/dev/gen-skill.js");
    process.exit(1);
  }
} else {
  fs.writeFileSync(file, out);
  console.log(`${commands.length} commands written`);
}
