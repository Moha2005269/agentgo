//! Typed registry of shell bridge methods.
//!
//! Every clickable control in the approved UI must map to a method here.
//! The registry records honest status per method: `Implemented` only when
//! the native handler exists; otherwise `Planned` (UI must render the
//! control disabled with a reason) — never a fake success.

use agentgo_policy::RiskClassifier;
use serde::{Deserialize, Serialize};

/// Honest implementation status of a bridge method.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum MethodStatus {
    /// Native handler is wired and covered by tests.
    Implemented,
    /// Contract exists; native handler lands in a later milestone.
    /// The UI must show the control disabled with a reason.
    Planned,
}

/// One command contract entry.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ShellMethod {
    /// Dotted method name, e.g. `act.click`.
    pub name: &'static str,
    /// One-line description used by the skill and docs.
    pub description: &'static str,
    /// Implementation status (honest).
    pub status: MethodStatus,
    /// Milestone that wires the native handler.
    pub milestone: u8,
    /// JSON schema id in `schemas/` describing `params`.
    pub params_schema: &'static str,
    /// Risk classification from the policy crate.
    pub risk: agentgo_policy::ActionRisk,
    /// Integration test that exercises the handler (empty when planned).
    pub test: &'static str,
}

